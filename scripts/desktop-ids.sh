#!/usr/bin/env bash
# Shared desktop install / data path helpers for GhalBol apps.
# Requires GHALBOL_APP_ID and GHALBOL_APP_LABEL (from the app's env/*.env).
# Per-app identity overrides: GHALBOL_INSTALL_SLUG, GHALBOL_BIN_NAME, GHALBOL_PROGRAMS_NAME.
# Default is GhalBol Chat's — existing installs must not move.
#
# Chat prod:  com.ghalbol       · "Ghal Bol"
# Chat dev:   com.ghalbol.debug · "Ghal Bol Dev"

desktop_is_debug() {
  [[ "${GHALBOL_APP_ID:-}" == *.debug ]] || [[ "${GHALBOL_ENV:-}" == "development" ]]
}

# Short folder slug under ~/.local/lib and for package layout (no spaces).
desktop_install_slug() {
  local base="${GHALBOL_INSTALL_SLUG:-ghalbol}"
  if desktop_is_debug; then
    echo "$base-dev"
  else
    echo "$base"
  fi
}

# Windows Programs folder name (spaces OK). The env label carries the Dev suffix.
desktop_programs_name() {
  echo "${GHALBOL_PROGRAMS_NAME:-${GHALBOL_APP_LABEL:-Ghal Bol}}"
}

# CLI / shortcut binary base name.
desktop_bin_name() {
  local base="${GHALBOL_BIN_NAME:-ghalbol-app}"
  if desktop_is_debug; then
    echo "$base-dev"
  else
    echo "$base"
  fi
}

# Freedesktop desktop file id (no .desktop suffix).
desktop_entry_id() {
  echo "${GHALBOL_APP_ID:-com.ghalbol}"
}

# Data directory paths.
desktop_data_dir_linux() {
  echo "${XDG_DATA_HOME:-$HOME/.local/share}/${GHALBOL_APP_ID:?}"
}

desktop_data_dir_windows_hint() {
  echo "%APPDATA%\\\\${GHALBOL_APP_ID:?}"
}

desktop_install_dir_linux() {
  if [[ -n "${DESKTOP_INSTALL_DIR_LINUX:-}" ]]; then
    echo "$DESKTOP_INSTALL_DIR_LINUX"
    return
  fi
  echo "$HOME/.local/lib/$(desktop_install_slug)"
}

desktop_bin_dir_linux() {
  echo "${XDG_BIN_HOME:-$HOME/.local/bin}"
}

desktop_applications_dir_linux() {
  echo "${XDG_DATA_HOME:-$HOME/.local/share}/applications"
}

# Write install manifest (re-runnable after partial delete).
desktop_write_manifest() {
  local dest="${1:?}"
  mkdir -p "$(dirname "$dest")"
  cat >"$dest" <<EOF
# Generated by GhalBol desktop install — do not edit unless you know why.
GHALBOL_ENV=${GHALBOL_ENV:-production}
GHALBOL_APP_ID=${GHALBOL_APP_ID:?}
GHALBOL_APP_LABEL=${GHALBOL_APP_LABEL:?}
INSTALL_SLUG=$(desktop_install_slug)
BIN_NAME=$(desktop_bin_name)
ENTRY_ID=$(desktop_entry_id)
INSTALLED_AT=$(date -u +%Y-%m-%dT%H:%M:%SZ)
EOF
}

desktop_load_manifest() {
  local file="${1:?}"
  [[ -f "$file" ]] || return 1
  while IFS= read -r line || [[ -n "$line" ]]; do
    line="${line#"${line%%[![:space:]]*}"}"
    [[ -z "$line" || "$line" == \#* ]] && continue
    [[ "$line" != *=* ]] && continue
    local key="${line%%=*}"
    local value="${line#*=}"
    export "$key=$value"
  done <"$file"
}

desktop_prompt_remove_data() {
  local data_dir="${1:?}"
  local label="${GHALBOL_APP_LABEL:-Ghal Bol}"
  echo
  echo "$label — local data:"
  echo "  $data_dir"
  if [[ ! -e "$data_dir" ]]; then
    echo "  (no data directory found — nothing to remove)"
    return 1
  fi
  echo
  echo "Remove this data? (settings, keystore backups)"
  echo "  y = delete data forever"
  echo "  N = keep data (run uninstall again later to remove it)"
  local ans=""
  if [[ -t 0 ]]; then
    read -r -p "Remove data? [y/N] " ans || true
  else
    echo "(non-interactive: keeping data)"
    ans="n"
  fi
  case "${ans,,}" in
    y|yes) return 0 ;;
    *) return 1 ;;
  esac
}
